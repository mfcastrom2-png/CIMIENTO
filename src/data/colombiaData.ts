export const getMunicipiosPorDepartamento = (departamentoNombre?: string): string[] => {
  if (!departamentoNombre) return [];
  const normalizado = departamentoNombre.trim().toLowerCase();
  const dep = DEPARTAMENTOS_COLOMBIA.find(d => 
    d.nombre.toLowerCase() === normalizado ||
    d.nombre.toLowerCase().replace(' d.c.', '') === normalizado.replace(' d.c.', '')
  );
  return dep ? dep.municipios : [];
};

export const getDepartamentoPorMunicipio = (municipioNombre?: string): string | undefined => {
  if (!municipioNombre) return undefined;
  const normalizado = municipioNombre.trim().toLowerCase();
  for (const dep of DEPARTAMENTOS_COLOMBIA) {
    if (dep.municipios.some(m => m.toLowerCase() === normalizado)) {
      return dep.nombre;
    }
  }
  return undefined;
};

